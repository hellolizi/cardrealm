/** 一座岛挨着哪些岛。用来判断「能不能从这儿出发」和「下一步去哪」。 */
export function seaNeighbours(regionId) {
  const out = [];
  for (const route of SEA_ROUTES) {
    if (route.from === regionId) out.push(route.to);
    else if (route.to === regionId) out.push(route.from);
  }
  return out;
}

