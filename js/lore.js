/** 取某段剧情在本局执牌者下真正要播的对白（含奶蛙蛙彩蛋）。 */
export function storyLines(storyId, originId) {
  const story = STORIES[storyId];
  if (!story) return [];
  const extra = originId === 'milkfrog' ? MILKFROG_STORY_LINES[storyId] : null;
  return extra && extra.length ? [...story.lines, ...extra] : story.lines;
}

/* ───────────────────────── 分支对话的读取 ───────────────────────── */

export function dialogueById(id) {
  return DIALOGUES[id] || null;
}

/** 这个角色现在能不能开口。已经在聊的、或者这条线播完的，都不再触发。 */
export function dialogueForNpc(world, npcId) {
  if (!world) return null;
  const seen = world.dialogues?.seen || [];
  const played = world.dialogues?.nodes || {};
  return Object.values(DIALOGUES).find((dialogue) => {
    if (dialogue.npc !== npcId) return false;
    if (seen.includes(dialogue.npc + ':' + dialogue.entry)) return false;
    return !played[dialogue.npc + ':' + dialogue.entry];
  }) || null;
}

export function dialogueNode(dialogueId, nodeId) {
  const dialogue = DIALOGUES[dialogueId];
  if (!dialogue) return null;
  const node = dialogue.nodes[nodeId];
  if (!node) return null;
  return {
    ...node,
    id: nodeId,
    npc: NPC_MAP[dialogue.npc] || null,
    faction: NPC_MAP[dialogue.npc]?.faction || 'neutral',
    dialogueTitle: dialogue.title,
    isEnd: !node.next && !(node.choices && node.choices.length),
  };
}

/** 玩家点了某个选项之后，下一个节点是谁。 */
export function dialogueNext(dialogueId, nodeId, choiceId) {
  const dialogue = DIALOGUES[dialogueId];
  const node = dialogue?.nodes?.[nodeId];
  if (!node) return null;
  const choice = (node.choices || []).find((item) => item.id === choiceId);
  if (!choice) return null;
  return { nodeId: choice.next || null, choice };
}

/** 阵营在界面上的说法。 */
export function factionOf(npcId) {
  return FACTIONS[NPC_MAP[npcId]?.faction] || FACTIONS.neutral;
}
