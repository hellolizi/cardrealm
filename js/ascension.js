function clampLevel(level) {
  return Math.max(0, Math.min(MAX_ASCENSION, Math.floor(Number(level) || 0)));
}

export function ascensionLevel(level) {
  return ASCENSION_LEVELS[clampLevel(level)];
}

export function ascensionModifiers(level) {
  const entry = ascensionLevel(level);
  return {
    enemyHpScale: Number(entry.enemyHpScale) || 1,
    enemyBonusDamage: Number(entry.enemyBonusDamage) || 0,
    enemyStartStrength: Number(entry.enemyStartStrength) || 0,
    enemyStartBlock: Number(entry.enemyStartBlock) || 0,
    enemyStartThorns: Number(entry.enemyStartThorns) || 0,
    drawPenalty: Number(entry.drawPenalty) || 0,
    energyPenalty: Number(entry.energyPenalty) || 0,
    noItems: Boolean(entry.noItems),
    goldScale: Number(entry.goldScale) || 1,
    restScale: Number(entry.restScale) || 1,
    shopPriceScale: Number(entry.shopPriceScale) || 1,
  };
}

export function ascensionLabel(level) {
  const entry = ascensionLevel(level);
  return `梦境层级 ${entry.level} · ${entry.name}`;
}

// 完成一层只解锁下一层；重复通关低层不会倒退，也不会跳过。
export function ascensionUnlockAfter(clearedLevel, unlockedLevel) {
  const cleared = clampLevel(clearedLevel);
  const unlocked = clampLevel(unlockedLevel);
  return Math.max(unlocked, Math.min(MAX_ASCENSION, cleared + 1));
}
